const cosa = (famiglia: string, s: Base): Scheda => ({ famiglia, tipo: 'oggetto', numero: 's', ...s });
const costruzione = (famiglia: string, s: Base): Scheda => ({ famiglia, tipo: 'costruzione', numero: 's', ...s });

