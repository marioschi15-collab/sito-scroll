import type { Scheda } from './scheda.js';

/**
 * Il cielo, una delle sei parti della grande infornata (P8): cielo, tempo, fenomeni, feste ed eventi che nascono
 * dalle unioni. Le sue voci hanno i numeri da 1100 a 1199 (`numeri.ts`). Solo dati: le chiavi sono testi, niente import
 * dal motore.
 *
 * Le unioni oltre la prima via seguono poche idee che chi gioca può indovinare e poi riusare:
 * - una cosa portata sulla notte diventa la luce che le somiglia lassù (il pozzo la luna, la giostra la luna del luna
 *   park, l'igloo e la slitta l'aurora del grande nord);
 * - ciò che gira, portato nella bufera, fa il tornado (il mulino, la girandola, la giostra);
 * - ciò che è di neve o di gelato, portato al sole o all'estate, fa una pozzanghera;
 * - «para-» vuol dire «ripara da»: l'ombrello col fulmine fa il parafulmine, il parafulmine con la pioggia il
 *   parapioggia, cioè l'ombrello;
 * - gli uccelli partono tutti insieme quando qualcosa dice «è sera» o «arriva il freddo» (l'autunno, l'eclissi, il
 *   termometro che scende);
 * - la festa, portata su una cosa, la fa diventare la cosa della festa (il pane la torta, la ruota la giostra, la
 *   torta il carnevale).
 * I fenomeni (dal sole alla pozzanghera) non si regalano con Unisci: le loro coppie sono vie nel mondo, e si
 * scoprono portando una cosa sull'altra là dentro. La notte, l'alba e gli altri fenomeni non si prendono in mano:
 * per questo ogni fenomeno ha almeno una via fatta di una cosa che si porta (un oggetto, un evento, un materiale)
 * e di una cosa che nel mondo c'è (l'estate portata sul fuoco fa il sole, il formaggio portato sul pozzo la luna,
 * come nella fiaba del lupo). Le due voci «finale» sono la rugiada, che sparisce col primo sole,
 * e il terremoto, che scuote e basta: punti d'arrivo voluti.
 */

type Base = Omit<Scheda, 'famiglia' | 'tipo' | 'numero'> & Partial<Pick<Scheda, 'numero'>>;

