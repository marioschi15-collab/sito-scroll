/** L'icona di una creatura: la sua figura, messa al centro di un quadrato di 12x12 quadretti. */
function iconaDa(figura: readonly string[]): string[] {
  const largo = Math.max(...figura.map((r) => r.length));
  const sx = (12 - largo) >> 1;
  const su = (12 - figura.length) >> 1;
  return Array.from({ length: 12 }, (_, y) => {
    const r = figura[y - su];
    return r === undefined ? '.'.repeat(12) : ('.'.repeat(sx) + r.padEnd(largo, '.')).padEnd(12, '.');
  });
}

