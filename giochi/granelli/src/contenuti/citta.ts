/**
 * La città, una delle sei parti della grande infornata (P8): città, commercio, leggi, arti, scrittura e saperi,
 * dall’antichità al medioevo. Le sue voci hanno i numeri da 800 a 899 (`numeri.ts`). Solo dati: le chiavi sono testi,
 * niente import dal motore.
 *
 * Le unioni oltre la prima via seguono una regola sola: ogni cosa della città chiama la persona o il posto che la
 * usa, e ogni persona porta la sua cosa nel posto giusto. Lo scriba prende la carta e ne fa una lettera, il re ci mette
 * il sigillo, il sigillo sulla pergamena fa la legge, il giudice con la bilancia entra nel tribunale. Così quasi ogni
 * voce entra in due unioni almeno. Le due voci segnate «finale» sono punti d'arrivo voluti: gli Scacchi, un gioco
 * che riassume il regno, e le Terme, il riposo della città finita.
 */

// Oggetti, costruzioni e idee stanno tutti nel capitolo «Città e saperi»; i mestieri nelle «Genti», con quelli di prima.
type Senza<K extends keyof Scheda> = Omit<Scheda, 'famiglia' | 'tipo' | 'numero' | K> & Partial<Pick<Scheda, 'numero'>>;
