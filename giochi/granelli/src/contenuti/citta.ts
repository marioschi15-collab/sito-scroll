const costruzione = (s: Senza<never>): Scheda => ({ famiglia: 'saperi', tipo: 'costruzione', numero: 's', ...s });
const idea = (s: Senza<never>): Scheda => ({ famiglia: 'saperi', tipo: 'idea', numero: 's', ...s });
const gente = (s: Senza<'genere'>): Scheda => ({ famiglia: 'genti', tipo: 'mestiere', numero: 's', genere: 'm', ...s });

