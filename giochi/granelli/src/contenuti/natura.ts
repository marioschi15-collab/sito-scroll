import type { Scheda } from './scheda.js';

/**
 * La natura, una delle sei parti della grande infornata (P8): piante, creature, paesaggi, stagioni e il cibo che
 * viene dalla terra. Le sue voci hanno i numeri da 600 a 699 (`numeri.ts`). Solo dati: le chiavi sono testi, niente
 * import dal motore.
 *
 * Le unioni in più seguono poche idee che chi gioca può indovinare e poi riusare:
 * - il cibo lasciato in casa chiama il topo, quello lasciato sul prato chiama le formiche;
 * - il topo portato su una cosa diventa il suo vicino di casa (sull'albero lo scoiattolo, sulla castagna il riccio,
 *   sulla carota il coniglio, in aria il pipistrello);
 * - un animale portato su una stagione la fa andare avanti, come fa lui nel mondo (le rondini tornano a primavera,
 *   l'orso va a dormire d'inverno, il cervo bramisce in autunno);
 * - chi vola di notte, portato sull'alba, diventa chi vola di giorno (il gufo l'aquila, il pipistrello la farfalla).
 */

/** L'icona di una creatura: la sua figura, messa al centro di un quadrato di 12x12 quadretti. */
function iconaDa(figura: readonly string[]): string[] {
  const largo = Math.max(...figura.map((r) => r.length));
  const sx = (12 - largo) >> 1;
  const su = (12 - figura.length) >> 1;
  return Array.from({ length: 12 }, (_, y) => {
    const r = figura[y - su];
    return r === undefined ? '.'.repeat(12) : ('.'.repeat(sx) + r.padEnd(largo, '.')).padEnd(12, '.');
  });
}

type Base = Omit<Scheda, 'famiglia' | 'tipo' | 'numero'>;

// Le piante: quelle da tenere in mano o da appoggiare sono oggetti, gli alberi e i filari sono costruzioni.
const pianta = (s: Base): Scheda => ({ famiglia: 'vita', tipo: 'oggetto', numero: 's', ...s });
const albero = (s: Base): Scheda => ({ famiglia: 'vita', tipo: 'costruzione', numero: 's', ...s });
const cibo = (s: Base): Scheda => ({ famiglia: 'cucina', tipo: 'oggetto', numero: 's', ...s });
const stagione = (s: Base): Scheda => ({ famiglia: 'feste', tipo: 'evento', numero: 's', ...s });
// Una creatura ha per icona la sua figura; le più piccole (la formica, il bruco) ne hanno una disegnata più grande.
const creatura = (s: Base): Scheda => ({
  famiglia: 'animali',
  tipo: 'creatura',
  numero: 's',
  ...s,
  icona: s.icona ?? iconaDa(s.figura!),
});

