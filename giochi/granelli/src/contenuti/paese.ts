import type { Scheda } from './scheda.js';

/**
 * Il paese: i mestieri e le persone che nascono portando una cosa a un omino, e le cose nate unendo le invenzioni
 * tra loro. Solo dati: le chiavi sono testi, i numeri stanno in `numeri.ts`.
 */

/**
 * L'icona di una persona: testa e spalle a sinistra, il segno del mestiere in basso a destra. `maglia` e `capelli`
 * sono lettere della tavolozza; `cappello` copre le prime righe (il punto lascia vedere sotto); `segno` è largo fino
 * a cinque quadretti e si appoggia sul fondo, a destra.
 */
export function persona(maglia: string, capelli: string, cappello: readonly string[], segno: readonly string[]): string[] {
  const busto = [
    '...hhhh.....',
    '..hhhhhh....',
    '..hpppph....',
    '..pkppkp....',
    '..pppppp....',
    '...pqqp.....',
    '....pp......',
    '.AAAAAAA....',
    'AAAAAAAAA...',
    'AAAAAAAAA...',
    'AAAAAAAAA...',
    'AAAAAAAAA...',
  ].map((r) => r.replaceAll('A', maglia).replaceAll('h', capelli).split(''));
  cappello.forEach((riga, y) => {
    for (let x = 0; x < riga.length; x++) if (riga[x] !== '.') busto[y][x] = riga[x];
  });
  const da = 12 - segno.length;
  segno.forEach((riga, k) => {
    for (let x = 0; x < riga.length; x++) if (riga[x] !== '.') busto[da + k][7 + x] = riga[x];
  });
  return busto.map((r) => r.join(''));
}

/** L'icona di chi fa un mestiere, e il segno del mestiere da solo: l'omino che lo fa lo porta sopra la testa. */
export function vestito(maglia: string, capelli: string, cappello: readonly string[], segno: readonly string[]): Pick<Scheda, 'icona' | 'segno'> {
  return { icona: persona(maglia, capelli, cappello, segno), segno };
}

